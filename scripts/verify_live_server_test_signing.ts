import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { createSession } from '../server/authService.ts';

async function testLiveServer() {
  console.log('========================================================================');
  console.log('TESTING LIVE HOSTED SERVER FOR LOCAL SIGNING IN TEST MODE');
  console.log('========================================================================\n');

  // 1. Authenticate with owner session
  console.log('1. Creating owner session token for test validation...');
  const token = createSession('amit2001tal@gmail.com', '127.0.0.1', 'IntegrationValidator/1.0');
  const headers = {
    'Cookie': `amit_session=${token}`,
    'Content-Type': 'application/json',
  };

  // 2. Query signing status
  console.log('\n2. Querying GET /api/documents/signing-status from live server...');
  const statusRes = await fetch('http://127.0.0.1:5173/api/documents/signing-status', { headers });
  const statusData = await statusRes.json();
  console.log('   Response Status:', statusRes.status);
  console.log('   isConfigured (Official Live):', statusData.isConfigured);
  console.log('   isTestModeSigningAvailable: ', statusData.isTestModeSigningAvailable);
  console.log('   signatureCategory:          ', statusData.signatureCategory);
  console.log('   legalAdvisory:              ', statusData.legalAdvisory);

  // 3. Negative check: Verify official customer receipt issuance remains strictly BLOCKED
  console.log('\n3. Verifying official customer receipt issuance is strictly blocked...');
  const officialRes = await fetch('http://127.0.0.1:5173/api/documents/issue', {
    method: 'POST',
    headers,
    body: JSON.stringify({
      documentId: 'doc_nonexistent_or_test',
      idempotencyKey: `test_official_block_${Date.now()}`,
      isTestMode: false // Attempting official issuance!
    })
  });
  const officialData = await officialRes.json();
  console.log('   Official Issuance Attempt Response Status:', officialRes.status);
  console.log('   Official Issuance Error:', officialData.error);

  // 4. Generate signed test receipt directly from live server
  console.log('\n4. Calling POST /api/documents/generate-test-receipt on live server...');
  const genRes = await fetch('http://127.0.0.1:5173/api/documents/generate-test-receipt', {
    method: 'POST',
    headers
  });
  const genData = await genRes.json();
  console.log('   Response Status:', genRes.status);
  console.log('   Success:', genData.success);
  console.log('   Document Number:', genData.document?.documentNumber);
  console.log('   isTestMode:', genData.document?.isTestMode);
  console.log('   isOfficial:', genData.document?.isOfficial);
  console.log('   Digital Signature Algorithm:', genData.document?.digitalSignature?.algorithm);
  console.log('   Signed PDF Filename:', genData.document?.signedPdfFilename);

  // 5. Download the exact signed PDF generated by the hosted server
  console.log('\n5. Downloading signed test PDF from live server endpoint...');
  const downloadUrl = `http://127.0.0.1:5173${genData.downloadUrl || '/api/documents/test-signed-pdf'}`;
  const pdfRes = await fetch(downloadUrl, { headers });
  console.log('   PDF Download Status:', pdfRes.status);
  const pdfArrayBuf = await pdfRes.arrayBuffer();
  const pdfBuffer = Buffer.from(pdfArrayBuf);
  console.log('   Downloaded PDF Size:', pdfBuffer.length, 'bytes');

  // Save the downloaded PDF from live server for independent validator verification
  const livePdfPath = path.resolve(process.cwd(), 'data', 'test_packages', 'receipt_live_server_signed.pdf');
  fs.writeFileSync(livePdfPath, pdfBuffer);
  console.log('   Saved live server PDF to:', livePdfPath);

  // Create tampered copy
  const tamperedBuffer = Buffer.from(pdfBuffer);
  tamperedBuffer[600] = tamperedBuffer[600] === 0x41 ? 0x42 : 0x41;
  const liveTamperedPath = path.resolve(process.cwd(), 'data', 'test_packages', 'receipt_live_server_tampered.pdf');
  fs.writeFileSync(liveTamperedPath, tamperedBuffer);
  console.log('   Saved tampered copy to:', liveTamperedPath);

  console.log('\nLive server test generation completed successfully!');
}

testLiveServer().catch(err => {
  console.error('Error during live server test:', err);
  process.exit(1);
});
